import XCTest

/// Launches the app in its deterministic UI-test mode (`-panop-uitest`): in-memory storage, a
/// seeded playlist of thirty channels, and an engine that "plays" at once, so these tests
/// drive the real screens with no network.
@MainActor
class PanopUITestCase: XCTestCase {
    var app: XCUIApplication!

    /// Seconds the player's controls stay up. Long, because a UI test is slower than the real
    /// four seconds; a test about the controls hiding overrides it.
    var controlsTimeout: Int {
        60
    }

    /// The tab the app opens on: Live TV, since most tests are about it.
    /// Gives Home a hero title, which the seeded library has no suggestions to choose from.
    var showsHero: Bool {
        false
    }

    /// Gives the hero a bright picture, to see how controls look over real artwork.
    var showsBrightArtwork: Bool {
        false
    }

    /// Fictional content with generated artwork, for the store screenshots (`Scripts/make-store-screenshots.sh`).
    var isDemo: Bool {
        false
    }

    /// The sports hub with the demo service: a key, leagues, teams and invented clubs (`SportsDemo`).
    var demoSports: Bool {
        false
    }

    /// A path to a file with a real sportapi.ai key, for a run against the real service (never in the repository: the
    /// key
    /// is in the git-ignored `.secrets`). Nil in every ordinary test.
    var devSportsKeyFile: String? {
        nil
    }

    /// The league ids to follow in a run against the real service, comma separated (`PANOP_DEV_SPORTS_LEAGUES`).
    var devSportsLeagues: String? {
        nil
    }

    /// A playlist file to import in place of the seeded one, to see the screens with a real catalog's size
    /// (`PANOP_SEED_FILE`). Generated by the developer, never committed.
    var seedFile: String? {
        nil
    }

    /// A YouTube id every film and series has as its trailer, to look at the trailer player (`PANOP_TRAILER`).
    var trailerID: String? {
        nil
    }

    var startTab: String {
        "live"
    }

    /// A language code to run the app in, such as `de`, or nil for the simulator's own.
    var launchLanguage: String? {
        nil
    }

    /// Seed a second version of the first channel, sharing its guide, and group the list by guide.
    var groupsByGuide: Bool {
        false
    }

    /// Seed the playlist as a live-only source, which hides the Movies and Series tabs.
    var liveOnly: Bool {
        false
    }

    override func setUpWithError() throws {
        continueAfterFailure = false
        // Driving a Mac app needs an accessibility grant that is only given interactively.
        #if os(macOS)
            throw XCTSkip("UI tests run on the iOS and tvOS simulators.")
        #endif
        app = XCUIApplication()
        // The app clears its remembered filters when it starts in this mode. They are not set
        // here as launch arguments: those pin a value, and the app could then never change it.
        app.launchArguments = ["-panop-uitest"]
        if let language = launchLanguage {
            app.launchArguments += ["-AppleLanguages", "(\(language))", "-AppleLocale", language]
        }
        app.launchEnvironment["PANOP_CONTROLS_TIMEOUT"] = String(controlsTimeout)
        app.launchEnvironment["PANOP_START_TAB"] = startTab
        if isDemo {
            app.launchEnvironment["PANOP_DEMO"] = "1"
            // The posters of the real films the demo shows, in the repository.
            app.launchEnvironment["PANOP_DEMO_ART_DIR"] = URL(fileURLWithPath: #filePath)
                .deletingLastPathComponent().deletingLastPathComponent()
                .appendingPathComponent("docs/store-art").path
        }
        if let file = devSportsKeyFile {
            app.launchEnvironment["PANOP_DEV_SPORTSAPI"] = file
        }
        if let devSportsLeagues {
            app.launchEnvironment["PANOP_DEV_SPORTS_LEAGUES"] = devSportsLeagues
        }
        if let seedFile {
            app.launchEnvironment["PANOP_SEED_FILE"] = seedFile
        }
        if let trailerID {
            app.launchEnvironment["PANOP_TRAILER"] = trailerID
        }
        if demoSports {
            app.launchEnvironment["PANOP_DEMO_SPORTS"] = "1"
        }
        if showsHero {
            app.launchEnvironment["PANOP_HERO"] = "1"
            if showsBrightArtwork {
                app.launchEnvironment["PANOP_HERO_ART"] = "1"
            }
        }
        if liveOnly {
            app.launchEnvironment["PANOP_LIVE_ONLY"] = "1"
        }
        if groupsByGuide {
            app.launchEnvironment["PANOP_VERSIONS"] = "1"
            app.launchArguments += ["-groupsByGuide", "YES"]
        }
        app.launch()
    }

    /// The list is alphabetical and lazy, so only the first rows exist on screen: `3sat`, then
    /// `Arte`. Tests that need a row look for those.
    ///
    /// A channel row, found by name. A row's label also carries its group.
    func channel(_ name: String) -> XCUIElement {
        app.buttons.matching(NSPredicate(format: "label CONTAINS %@", name)).firstMatch
    }

    #if !os(tvOS)
        /// Scrolls until `element` is in the accessibility tree: Settings is a long list, and a row below the fold is
        /// not
        /// there yet.
        func scrollTo(_ element: XCUIElement) {
            for _ in 0 ..< 6 where !element.exists {
                app.swipeUp()
            }
        }

        /// Opens Settings: its tab where there is one, and on a phone the button on Home, which has no room for the
        /// tab.
        func openSettings(named name: String = "Settings") {
            let tab = app.tabBars.buttons[name]
            if tab.exists {
                tab.tap()
            } else {
                app.tabBars.buttons.element(boundBy: 0).tap()
                app.buttons[name].tap()
            }
        }
    #endif

    func waitForChannels(file: StaticString = #filePath, line: UInt = #line) {
        let found = channel("3sat").waitForExistence(timeout: 30)
        // On a miss, what the screen held is the only clue to why.
        XCTAssertTrue(
            found,
            "the seeded playlist never appeared. Screen:\n\(app.debugDescription)",
            file: file,
            line: line
        )
    }

    #if os(tvOS)
        /// Focus starts on the tab bar. Down from there reaches the search magnifier, then the TV Guide
        /// button, the Show filter, the Sort row, the category chips, then the first channel. Pressed until the
        /// channel has focus, not counted, so a row added above it does not break every test that follows.
        func focusFirstChannel() {
            focus(channel("Das Erste"))
        }

        /// Moves down until one of the buttons with this label has focus, for a label the tree holds more than once.
        func focusButton(labelled label: String) {
            // In a list the focused thing can be the row (a cell) that holds the button, not the button.
            let matches = app.descendants(matching: .any).matching(NSPredicate(
                format: "label == %@ AND (elementType == %d OR elementType == %d)",
                label,
                XCUIElement.ElementType.button.rawValue,
                XCUIElement.ElementType.cell.rawValue
            ))
            // The focus can sit on a part inside the button (its icon, its text), which does not report its parent as
            // focused: it is found by where it is.
            func focusIsOnOne() -> Bool {
                let buttons = matches.allElementsBoundByIndex
                if buttons.contains(where: \.hasFocus) {
                    return true
                }
                let frames = buttons.map(\.frame).filter { !$0.isEmpty }
                let focused = app.descendants(matching: .any).matching(NSPredicate(format: "hasFocus == true"))
                    .allElementsBoundByIndex
                return focused.contains { element in frames.contains { $0.intersects(element.frame) } }
            }
            for _ in 0 ..< 14 where !focusIsOnOne() {
                // Down from a wide control lands on whatever is nearest below its middle, which can be another button
                // of the row the one wanted is in (Sort, for TV Guide): then it is to the left.
                let target = matches.allElementsBoundByIndex.map(\.frame).first { !$0.isEmpty }
                let focused = app.descendants(matching: .any).matching(NSPredicate(format: "hasFocus == true"))
                    .allElementsBoundByIndex.map(\.frame)
                if let target, focused.contains(where: { abs($0.minY - target.minY) < 40 && $0.minX > target.maxX }) {
                    XCUIRemote.shared.press(.left)
                } else {
                    XCUIRemote.shared.press(.down)
                }
            }
        }

        /// Moves down until `element` has focus, up to a dozen presses.
        func focus(_ element: XCUIElement) {
            for _ in 0 ..< 12 where !(element.exists && element.hasFocus) {
                XCUIRemote.shared.press(.down)
            }
        }
    #endif
}
